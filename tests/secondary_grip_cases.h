// Actual grip adapter/state checks. Hand::Update actuation placement is audited
// in the extractor; synthetic hands do not qualify the Skyrim pose solver.
void SecondaryGripFixture(uint64_t owner)
{
    using namespace HiggsHands;
    fixturePlayer.actorState.drawn = false;
    fixturePlayer.equipment[0] = fixturePlayer.equipment[1] = nullptr;
    ammo = nullptr;
    fixtureLeft.holding = fixtureRight.holding = false;
    fixtureLeft.secondary = fixtureRight.secondary = false;
    PublishNative();
    uint64_t executor = 0;
    CHECK(!Service().Executor(owner, [](const HIGGS_ActionRequest *, void *) {}, nullptr, executor));
    HIGGS_HandUseRequest session{};
    session.structSize = sizeof(session);
    session.kind = HIGGS_USE_SECONDARY_SUPPORT;
    session.physicalHands = HIGGS_HAND_LEFT;
    session.durationMs = 5000;
    session.epoch = Service().Epoch();
    session.executor = executor;
    HIGGS_HandUseState use{};
    CHECK(!Service().HandUse(owner, session, use, Now()));
    TESObjectWEAP weapon;
    weapon.formID = 1001;
    fixtureLeft.twoHandedState.weapon = &weapon;
    fixtureLeft.secondary = true;
    fixtureLeft.synergySecondaryEpisode = 1;
    fixtureLeft.grabbedTime = 77;
    fixtureLeft.grabTransform.pos.x = 5;
    PublishNative();
    HIGGS_HandOperation operation{};
    operation.structSize = sizeof(operation);
    operation.kind = HIGGS_OP_GRIP_TRANSFORM;
    operation.physicalHand = HIGGS_HAND_LEFT;
    operation.itemRefId = weapon.formID;
    operation.epoch = Service().Epoch();
    operation.handGeneration = Service().HandGeneration(HIGGS_HAND_LEFT);
    operation.durationMs = 1000;
    operation.rotation[0] = operation.rotation[4] = operation.rotation[8] = 1;
    operation.scale = 1;
    operation.position[0] = 9;
    uint64_t id = 0;
    CHECK(Service().Operation(owner, operation, id, Now()) == HIGGS_HAND_CONFLICT);
    operation.grant = use.authority.grant;
    HIGGS_HandClientInfo info{};
    info.structSize = sizeof(info);
    std::snprintf(info.name, sizeof(info.name), "foreign grip");
    uint64_t foreign = 0;
    CHECK(!Service().Register(info, foreign));
    CHECK(Service().Operation(foreign, operation, id, Now()) != HIGGS_HAND_OK);
    CHECK(!Service().Operation(owner, operation, id, Now()));
    DrainNative();
    CHECK(fixtureLeft.grabTransform.pos.x == 9);
    HIGGS_ActionResult result{};
    CHECK(!Service().Result(owner, id, result) && result.stage == HIGGS_ACTION_COMMITTED);
    ConfirmNativeGrip(true);
    CHECK(!Service().Result(owner, id, result) && (result.receiptFlags & HIGGS_RECEIPT_PHYSICAL_CONFIRMED));
    CHECK(!Service().EndOperation(owner, id, operation.epoch));
    DrainNative();
    CHECK(fixtureLeft.grabTransform.pos.x == 5);
    // A same-frame stop/regrab can reuse grabbedTime and the same weapon.
    // Its monotonic native episode must reject already queued old-support work.
    CHECK(!Service().Operation(owner, operation, id, Now()));
    ++fixtureLeft.synergySecondaryEpisode;
    fixtureLeft.grabTransform.pos.x = 23;
    DrainNative();
    CHECK(fixtureLeft.grabTransform.pos.x == 23);
    CHECK(!Service().Result(owner, id, result) && result.stage == HIGGS_ACTION_CANCELLED);
    PublishNative();
    operation.handGeneration = Service().HandGeneration(HIGGS_HAND_LEFT);
    CHECK(!Service().Operation(owner, operation, id, Now()));
    DrainNative();
    fixtureLeft.grabTransform.pos.x = 19;
    CHECK(!Service().EndOperation(owner, id, operation.epoch));
    DrainNative();
    CHECK(fixtureLeft.grabTransform.pos.x == 19);
    CHECK(!Service().Operation(owner, operation, id, Now()));
    DrainNative();
    TESObjectWEAP replaced;
    replaced.formID = 1002;
    fixtureLeft.twoHandedState.weapon = &replaced;
    ValidateOperations();
    CHECK(!Service().OperationActive(id, Now()));
    CHECK(fixtureLeft.grabTransform.pos.x == 9);
    CHECK(!Service().Release(owner, use.authority.grant));
    fixtureLeft.secondary = false;
    PublishNative();
    // Two real-world holds have distinct per-Hand desired transforms/constraints.
    TESForm base;
    base.formID = 1100;
    TESObjectREFR reference;
    reference.formID = 1101;
    reference.baseForm = &base;
    forms[1101] = &reference;
    fixtureLeft.holding = fixtureRight.holding = true;
    fixtureLeft.selectedObject.handle = fixtureRight.selectedObject.handle = 1101;
    fixtureLeft.grabTransform.pos.x = 3;
    fixtureRight.grabTransform.pos.x = 4;
    PublishNative();
    operation.itemRefId = 1101;
    operation.grant = 0;
    operation.handGeneration = Service().HandGeneration(1);
    operation.position[0] = 11;
    CHECK(!Service().Operation(owner, operation, id, Now()));
    auto rightOperation = operation;
    rightOperation.physicalHand = 2;
    rightOperation.handGeneration = Service().HandGeneration(2);
    rightOperation.position[0] = 12;
    uint64_t rightId = 0;
    CHECK(!Service().Operation(owner, rightOperation, rightId, Now()));
    DrainNative();
    CHECK(fixtureLeft.grabTransform.pos.x == 11 && fixtureRight.grabTransform.pos.x == 12);
    CHECK(!Service().EndOperation(owner, id, operation.epoch));
    DrainNative();
    CHECK(fixtureLeft.grabTransform.pos.x == 3 && fixtureRight.grabTransform.pos.x == 12);
    CHECK(!Service().EndOperation(owner, rightId, operation.epoch));
    DrainNative();
    CHECK(fixtureRight.grabTransform.pos.x == 4);
    std::puts("PASS actual grip source: active secondary generation/weapon/grant, foreign writes/weapon replacement, "
              "independent two-hand transforms and owned restore");
}
