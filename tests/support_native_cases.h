int main()
{
    using namespace HiggsHands;
    hkpWorld engineWorld;
    bhkWorld world;
    world.world = &engineWorld;
    currentWorld = &world;
    fixturePlayer.parentCell = &world;
    NiAVObject handNode;
    fixtureLeft.node = &handNode;
    hkpRigidBody handBody;
    bhkRigidBody handWrapper;
    handWrapper.hkBody = &handBody;
    fixtureLeft.handBody = &handWrapper;
    NiNode model;
    TESObjectREFR target;
    target.formID = 99;
    target.node = &model;
    forms[99] = &target;
    hkpRigidBody targetBody;
    hkpShape shape;
    targetBody.world = &engineWorld;
    targetBody.collider.m_shape = &shape;
    bhkRigidBody targetWrapper;
    targetWrapper.hkBody = &targetBody;
    rootBodies[&model] = &targetWrapper;
    HIGGS_HandClientInfo info{};
    info.structSize = sizeof(info);
    std::snprintf(info.name, sizeof(info.name), "native support");
    uint64_t owner = 0;
    CHECK(!Service().Register(info, owner));
    Service().ObserveWorld(1, false, Now());
    std::array<HIGGS_HandRecord, 2> records{};
    for (auto &record : records)
        record.observationMask =
            HIGGS_OBS_HELD_KNOWN | HIGGS_OBS_EQUIPMENT_KNOWN | HIGGS_OBS_PALM_VALID | HIGGS_OBS_TRACKING_VALID;
    Service().Publish(records, Now());
    InitializeNativeSupport(nullptr, 0);
    const auto requestFor = [&](uint32_t kind) {
        HIGGS_SupportRequest request{};
        request.structSize = sizeof(request);
        request.kind = kind;
        request.physicalHand = HIGGS_HAND_LEFT;
        request.durationMs = 1000;
        request.epoch = Service().Epoch();
        request.handGeneration = Service().HandGeneration(HIGGS_HAND_LEFT);
        request.referenceFormId = 99;
        request.maxObservationAgeMs = 100;
        request.targetLocalRotation[0] = request.targetLocalRotation[4] = request.targetLocalRotation[8] = 1;
        request.maxDistanceWorld = 20;
        request.linearForceCap = 123;
        request.angularForceCap = 45;
        return request;
    };
    uint64_t id = 0;
    auto request = requestFor(HIGGS_SUPPORT_MOVING_WORLD);
    CHECK(!Supports().Request(owner, request, id, Now()));
    DrainNativeSupport();
    HIGGS_SupportState state{};
    CHECK(!Supports().Copy(owner, id, state));
    CHECK(state.stage == HIGGS_SUPPORT_ACTIVE && !(state.flags & HIGGS_SUPPORT_NATIVE_APPLIED));
    float position[3], rotation[9], scale = 0;
    CHECK(CopySupportTarget(true, position, rotation, scale));
    targetBody.transform.m_translation.x = *g_havokWorldScale;
    DrainNativeSupport();
    CHECK(CopySupportTarget(true, position, rotation, scale));
    CHECK(std::fabs(position[0] - 1.f) < .00001f);
    ConfirmSupportTarget(true);
    CHECK(!Supports().Copy(owner, id, state));
    CHECK(state.flags & HIGGS_SUPPORT_NATIVE_APPLIED);
    hkpShape replacement;
    targetBody.collider.m_shape = &replacement;
    DrainNativeSupport();
    CHECK(!CopySupportTarget(true, position, rotation, scale));
    DrainNativeSupport();
    CHECK(!Supports().Copy(owner, id, state));
    CHECK(state.stage == HIGGS_SUPPORT_BROKEN);
    hkpRigidBody sourceBody;
    sourceBody.world = &engineWorld;
    sourceBody.collider.m_shape = &shape;
    bhkRigidBody sourceWrapper;
    sourceWrapper.hkBody = &sourceBody;
    TESObjectREFR held;
    held.formID = 88;
    forms[88] = &held;
    fixtureLeft.holding = true;
    fixtureLeft.selectedObject.handle = 88;
    fixtureLeft.selectedObject.rigidBody = &sourceWrapper;
    records[0].heldRefId = 88;
    Service().Publish(records, Now());
    request = requestFor(HIGGS_CONSTRAINT_HELD_TO_WORLD);
    request.sourceItemRefId = 88;
    CHECK(!Supports().Request(owner, request, id, Now()));
    DrainNativeSupport();
    CHECK(constraintsAdded == 1 && arrayAdds == 1);
    CHECK(!Supports().Copy(owner, id, state));
    CHECK(state.flags & HIGGS_SUPPORT_CONSTRAINT_ATTACHED);
    CHECK(nativeConstraints.back()->owned.data.linear.maximum == 123 &&
          nativeConstraints.back()->owned.data.angular.maximum == 45);
    CHECK(!Supports().End(owner, id, request.epoch));
    DrainNativeSupport();
    CHECK(constraintsRemoved == 1 && arrayRemoves == 1 && fixtureLeft.holding);
    CHECK(!Supports().Copy(owner, id, state));
    CHECK(state.stage == HIGGS_SUPPORT_RELEASED);
    fixtureLeft.holding = false;
    records[0].heldRefId = 0;
    Service().Publish(records, Now());
    static PlanckSynergyAPI observed{};
    static PlanckPhysicalInteropAPI borrowed{};
    static hkpRigidBody *borrowedBody = &targetBody;
    static hkpWorld *borrowedWorld = &engineWorld;
    static unsigned releases = 0;
    static PlanckToken nextLease = 10;
    observed.AcquireAttachmentEndpoint = [](uint64_t client, const PlanckEndpointQuery *query,
                                            PlanckEndpoint *endpoint) -> PlanckStatus {
        CHECK(client == 123 && readLocks == 0);
        endpoint->size = sizeof(*endpoint);
        endpoint->lease = nextLease++;
        endpoint->body = query->body;
        return PLANCK_OK;
    };
    observed.ReleaseLease = [](uint64_t client, uint64_t) -> PlanckStatus {
        CHECK(client == 123 && readLocks == 0);
        ++releases;
        return PLANCK_OK;
    };
    borrowed.WithAttachmentEndpoint = [](uint64_t client, uint64_t lease, PlanckEndpointVisitor visitor,
                                         void *context) -> PlanckStatus {
        CHECK(client == 123 && readLocks == 0);
        BSWriteLocker lock(&currentWorld->worldLock);
        PlanckNativeEndpoint endpoint{};
        endpoint.size = sizeof(endpoint);
        endpoint.phase = PLANCK_PHASE_MAIN;
        endpoint.endpoint.lease = lease;
        endpoint.rigidBody = reinterpret_cast<uint64_t>(borrowedBody);
        endpoint.world = reinterpret_cast<uint64_t>(borrowedWorld);
        endpoint.geometryRevision = 7;
        return visitor(&endpoint, context);
    };
    planck = &observed;
    interop = &borrowed;
    planckClient = 123;
    Supports().Install(Driver, nullptr, UINT64_C(1) << 1);
    request = requestFor(HIGGS_SUPPORT_PLANCK_HAND);
    request.providerBody = {1, 2, 3, 4, 5};
    request.expectedGeometryRevision = 7;
    CHECK(!Supports().Request(owner, request, id, Now()));
    DrainNativeSupport();
    CHECK(CopySupportTarget(true, position, rotation, scale));
    uint64_t lease = Find(id)->lease;
    PlanckEvent invalidation{};
    invalidation.type = PLANCK_ENDPOINT_INVALIDATED;
    invalidation.subject = lease;
    Invalidated(&invalidation, nullptr);
    CHECK(!CopySupportTarget(true, position, rotation, scale));
    DrainNativeSupport();
    CHECK(releases == 1);
    CHECK(!Supports().Copy(owner, id, state));
    CHECK(state.stage == HIGGS_SUPPORT_BROKEN);
    std::puts("PASS actual native support source: moving anchor, shape identity, borrowed PLANCK lease/invalidation, "
              "owned constraint caps and removal (synthetic seams, not game qualification)");
}
